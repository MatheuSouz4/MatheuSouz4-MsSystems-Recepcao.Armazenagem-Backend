CREATE TABLE fornecedor (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razao_social  VARCHAR(200) NOT NULL,
    nome_fantasia VARCHAR(200),
    cnpj          VARCHAR(14)  NOT NULL,
    email         VARCHAR(150),
    telefone      VARCHAR(20),
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_fornecedor_cnpj UNIQUE (cnpj)
);

CREATE TABLE materia_prima (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(150) NOT NULL,
    descricao     VARCHAR(500),
    categoria     VARCHAR(30)  NOT NULL,
    fornecedor_id BIGINT       NOT NULL,
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_materia_prima_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES fornecedor (id),
    CONSTRAINT uk_materia_prima_fornecedor_nome UNIQUE (fornecedor_id, nome),
    CONSTRAINT ck_materia_prima_categoria CHECK (categoria IN ('ORIGEM_ANIMAL_OA', 'ORIGEM_VEGETAL_OV', 'MINERAL_MICRO_MI'))
);

CREATE INDEX idx_materia_prima_fornecedor ON materia_prima (fornecedor_id);

CREATE TABLE local_armazenagem (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo              VARCHAR(10)   NOT NULL,
    rua               VARCHAR(20)   NOT NULL,
    posicao           VARCHAR(20)   NOT NULL,
    capacidade_maxima NUMERIC(14,3) NOT NULL,
    ativo             BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_local_armazenagem UNIQUE (tipo, rua, posicao),
    CONSTRAINT ck_local_armazenagem_tipo CHECK (tipo IN ('ARMAZEM', 'SILO')),
    CONSTRAINT ck_local_armazenagem_capacidade CHECK (capacidade_maxima > 0)
);
